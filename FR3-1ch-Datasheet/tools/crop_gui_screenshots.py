"""Crops the user's GUI 1.4.1 screenshots (2026-10-10, Unit #6: FR1 1 GHz, FR3 9 GHz, upper sideband) into the four section
images of the "Using the Pi-Radio GUI" appendix, and writes the callout positions on them.

    python tools/crop_gui_screenshots.py [--shots-dir %USERPROFILE%/Downloads]

Inputs: Capture90.PNG (Configuration Helper + Clocking and LO), Capture91.PNG (TX + RX Settings).
Outputs: images/gui_shot_{helper,clocking,tx,rx}.png and sections/gui_shot_callouts.tex (\\guiCO<n>{X,Y}: fractions of
the section image, x from the left, y from the bottom; <n> = One..Eight).
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

DATASHEET = Path(__file__).resolve().parent.parent

# (source file, crop box left, top, right, bottom) in screenshot pixels -- each box is one section's frame (gold
# border located in the real pixels; the gold frames sit at rows 233/1215 and 1302/1929 of Capture90, 85/598 and
# 685/919 of Capture91)
CROPS = {
    "helper": ("Capture90.PNG", (64, 186, 1752, 1222)),
    "clocking": ("Capture90.PNG", (64, 1250, 1752, 1936)),
    "tx": ("Capture91.PNG", (68, 36, 1755, 605)),
    "rx": ("Capture91.PNG", (68, 636, 1755, 926)),
}
# callout -> (section, x, y) in screenshot pixels: the control it points at (marker drawn just to its left)
CALLOUTS = {
    "One": ("helper", 88, 281),        # FR1 / FR3 / bandwidth / sideband inputs
    "Two": ("helper", 989, 485),       # "Suggested Filter: 0x3E" graph title
    "Three": ("clocking", 295, 1463),  # Automatic drive checkbox
    "Four": ("clocking", 103, 1599),   # Lock status / temperature
    "Five": ("clocking", 103, 1778),   # Clock source and LO source
    "Six": ("tx", 150, 263),           # Automatic LO suppression checkbox
    "Seven": ("tx", 130, 513),         # TX "Use the Configuration Helper's suggested filter"
    "Eight": ("rx", 130, 834),         # RX "Use the Configuration Helper's suggested filter"
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--shots-dir", default=str(Path.home() / "Downloads"))
    args = ap.parse_args()
    for name, (src, box) in CROPS.items():
        Image.open(Path(args.shots_dir) / src).convert("RGB").crop(box).save(DATASHEET / "images" / f"gui_shot_{name}.png")
    lines = ["% generated by tools/crop_gui_screenshots.py -- do not edit",
             "% callout positions on images/gui_shot_<section>.png: fractions, x from the left, y from the bottom"]
    for n, (sec, x, y) in CALLOUTS.items():
        l, t, r, b = CROPS[sec][1]
        lines += [f"\\newcommand{{\\guiCO{n}X}}{{{(x - l) / (r - l):.4f}}}",
                  f"\\newcommand{{\\guiCO{n}Y}}{{{1 - (y - t) / (b - t):.4f}}}"]
    (DATASHEET / "sections" / "gui_shot_callouts.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", ", ".join(f"gui_shot_{k}.png" for k in CROPS), "and sections/gui_shot_callouts.tex")


if __name__ == "__main__":
    main()
