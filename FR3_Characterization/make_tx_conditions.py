"""Writes FR3-1ch-Datasheet/sections/sec_tx_conditions.tex: the measurement conditions every TX section quotes (the LMX
drive rule and the LMX die temperature range of each section's run), read from the runs themselves.

    python make_tx_conditions.py

Also defines \\attn{...} (red, bold): marks things in the datasheet text that need the author's attention.
"""
from __future__ import annotations

import csv
import glob

from plot_datasheet_nf import DATASHEET
from results_layout import unit_dir

U = unit_dir(5)
D9 = U / "2026-10-09"
RUNS = {  # macro prefix: (csv path pattern, temperature column)
    "Gain": (str(U / "gain_tx_20261009" / "points.csv"), "lmx_temp_c"),
    "Flat": (str(U / "flatness_tx_20261009" / "points.csv"), "lmx_temp_c"),
    "Sb": (str(U / "sideband_tx_20261009" / "points.csv"), "lmx_temp_c"),
    "Comp": (str(U / "compression_tx_20261009" / "summary.csv"), "lmx_temp_c"),
    "LoHot": (str(D9 / "lo_cal_grid_100MHz_*_full_cal_hot_drive_rule_table.csv"), "lmx_temp_c"),
    "TwoLo": (str(D9 / "lo_cal_grid_100MHz_*_sec10_1_2lo_hot_table.csv"), "lmx_temp_c"),
}


def main() -> None:
    lines = ["% generated by FR3_Characterization/make_tx_conditions.py -- do not edit",
             r"\providecommand{\attn}[1]{\textcolor{red}{\textbf{#1}}}",
             r"\newcommand{\lmxDriveRule}{LMX2820 drive level 0 for LO frequencies up to 13\,GHz, 2 from above 13 to below "
             r"20\,GHz, and 4 from 20\,GHz up}"]
    for tag, (pat, col) in RUNS.items():
        files = sorted(glob.glob(pat))
        if not files:
            lines += [f"\\newcommand{{\\cond{tag}MinC}}{{\\attn{{??}}}}", f"\\newcommand{{\\cond{tag}MaxC}}{{\\attn{{??}}}}"]
            continue
        t = [float(r[col]) for r in csv.DictReader(open(files[-1], newline=""))]
        lines += [f"\\newcommand{{\\cond{tag}MinC}}{{{min(t):.0f}}}", f"\\newcommand{{\\cond{tag}MaxC}}{{{max(t):.0f}}}"]
        print(f"{tag}: {files[-1]}: {min(t):.1f}-{max(t):.1f} C")
    (DATASHEET / "sections" / "sec_tx_conditions.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
