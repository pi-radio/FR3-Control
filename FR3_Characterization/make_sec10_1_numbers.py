"""Writes FR3-1ch-Datasheet/sections/sec_2lo_numbers.tex: the TX 2xLO spur numbers (datasheet 10.1 and the Key Specifications
row) from the all-filter-settings sweep (lo_cal_grid_scan.py --read-2lo): at each LO a fresh null with the reference filter,
then the 2xLO read in every usable filter setting (reference kept), no input signal.

    python make_sec10_1_numbers.py [--table <..._sec10_1_2lo_hot_table.csv>]
"""
from __future__ import annotations

import argparse
import csv
import glob
import statistics as st

from plot_datasheet_nf import DATASHEET

DEFAULT = r"results\unit_005\2026-10-09\lo_cal_grid_100MHz_*_sec10_1_2lo_hot_table.csv"
M = "−"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", default="")
    args = ap.parse_args()
    tpath = args.table or sorted(glob.glob(DEFAULT))[-1]
    t = list(csv.DictReader(open(tpath, newline="")))
    rows = list(csv.DictReader(open(tpath.replace("_table.csv", "_states.csv"), newline="")))
    v = [float(r["two_lo_dbm"]) for r in rows]
    worst = max(rows, key=lambda r: float(r["two_lo_dbm"]))
    temps = [float(r["lmx_temp_c"]) for r in t]
    los = [float(r["lo_ghz"]) for r in t]
    neg = lambda x: f"{x:.1f}".replace("-", M)
    macros = {
        "twoLoLoMin": f"{min(los):g}", "twoLoLoMax": f"{max(los):g}", "twoLoLoCount": str(len(t)),
        "twoLoReadCount": str(len(v)), "twoLoMedian": neg(st.median(v)), "twoLoMax": neg(max(v)),
        "twoLoMaxLo": f"{float(worst['lo_ghz']):g}", "twoLoMaxFilter": worst["tx_filter"],
        "twoLoAboveTwenty": str(sum(x > -20 for x in v)),
        "twoLoAboveLoMin": f"{min(float(r['lo_ghz']) for r in rows if float(r['two_lo_dbm']) > -20):g}",
        "twoLoAboveLoMax": f"{max(float(r['lo_ghz']) for r in rows if float(r['two_lo_dbm']) > -20):g}", "twoLoMinC": f"{min(temps):.0f}", "twoLoMaxC": f"{max(temps):.0f}",
    }
    lines = [f"% generated by FR3_Characterization/make_sec10_1_numbers.py from {tpath} -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{x}}}" for k, x in macros.items()]
    (DATASHEET / "sections" / "sec_2lo_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(macros)


if __name__ == "__main__":
    main()
