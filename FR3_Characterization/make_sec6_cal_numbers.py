"""Writes FR3-1ch-Datasheet/sections/sec6_cal_numbers.tex (the LO-suppression section's numbers) from the cold and hot
100 MHz-grid calibration scans at the LMX drive rule (lo_cal_tables.COLD / HOT). A temperature whose scan does not exist yet
gets red \\attn placeholders, so the datasheet shows clearly what is missing.

    python make_sec6_cal_numbers.py
"""
from __future__ import annotations

import csv
import glob
import statistics as st
from pathlib import Path

from lo_cal_tables import COLD, HOT
from plot_datasheet_lo_cal import THRESHOLD_DBM

OUT = Path(__file__).resolve().parent.parent / "FR3-1ch-Datasheet" / "sections" / "sec6_cal_numbers.tex"
M = "−"
MISSING = r"\attn{[pending]}"


def stats(patterns: list[str]) -> dict | None:
    files = sorted(f for pat in patterns for f in glob.glob(pat))
    if not files:
        return None
    tpath = files[-1]
    t = list(csv.DictReader(open(tpath, newline="")))
    rows = list(csv.DictReader(open(tpath.replace("_table.csv", "_states.csv"), newline="")))
    v = [float(r["lo_dbm_ref_bias"]) for r in rows]
    nr = [float(r["lo_dbm_ref_bias"]) for r in rows if r["is_reference"] != "1"]
    ref = [float(r["lo_dbm_ref_bias"]) for r in rows if r["is_reference"] == "1"]
    temps = [float(r["lmx_temp_c"]) for r in t]
    return {"file": tpath, "n_lo": len(t), "n": len(v), "pct": f"{100 * sum(x <= THRESHOLD_DBM for x in v) / len(v):.1f}",
            "median": neg(st.median(nr)), "worst": neg(max(nr)), "ref_median": st.median(ref),
            "tmin": f"{min(temps):.0f}", "tmax": f"{max(temps):.0f}", "minutes": f"{sum(float(r['seconds']) for r in t) / 60:.0f}"}


def neg(x: float) -> str:
    return f"{x:.0f}".replace("-", M)


def main() -> None:
    c, h = stats(COLD), stats(HOT)
    if h is None:
        raise SystemExit("no hot scan at the drive rule")
    cc = c or {k: MISSING for k in ("pct", "median", "worst", "tmin", "tmax")}
    refs = [x["ref_median"] for x in (c, h) if x]
    lines = [
        "% generated by FR3_Characterization/make_sec6_cal_numbers.py -- do not edit",
        f"% hot: {h['file']}", f"% cold: {c['file'] if c else 'NOT MEASURED YET (needs the fan on)'}",
        r"\providecommand{\attn}[1]{\textcolor{red}{\textbf{#1}}}",
        r"\providecommand{\ph}[1]{\textcolor{red}{\textbf{[#1]}}}",
        r"\newcommand{\calLoCount}{156}",
        f"\\newcommand{{\\calReadCount}}{{{h['n']}}}",
        f"\\newcommand{{\\calThreshold}}{{{neg(THRESHOLD_DBM)}}}",
        r"\newcommand{\calPassPct}{85}",                       # pass rule changed 90 -> 85 % (user, 2026-10-09)
        f"\\newcommand{{\\calColdMinC}}{{{cc['tmin']}}}", f"\\newcommand{{\\calColdMaxC}}{{{cc['tmax']}}}",
        f"\\newcommand{{\\calHotMinC}}{{{h['tmin']}}}", f"\\newcommand{{\\calHotMaxC}}{{{h['tmax']}}}",
        f"\\newcommand{{\\calColdPct}}{{{cc['pct']}}}", f"\\newcommand{{\\calHotPct}}{{{h['pct']}}}",
        f"\\newcommand{{\\calColdMedian}}{{{cc['median']}}}", f"\\newcommand{{\\calHotMedian}}{{{h['median']}}}",
        f"\\newcommand{{\\calColdWorst}}{{{cc['worst']}}}", f"\\newcommand{{\\calHotWorst}}{{{h['worst']}}}",
        f"\\newcommand{{\\calRefMedian}}{{{neg(st.median(refs))}}}",
        f"\\newcommand{{\\calMinutesPerTemp}}{{{h['minutes']}}}",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT)
    print(f"hot: {h}\ncold: {c}")


if __name__ == "__main__":
    main()
