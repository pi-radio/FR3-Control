"""Datasheet figures, table and numbers for the Phase Noise section, from the phase_noise_capture.py runs
(results/unit_<n>/phase_noise/lo<GHz>GHz_zero_dbm_*.csv, one run per LO frequency).

    python plot_datasheet_pn.py [--unit 5]

Writes FR3-1ch-Datasheet/images/sec14_fig{1..N}.pdf (one per LO, ascending), sections/sec14_table.tex (the
decade-offset table) and sections/sec14_numbers.tex (macros quoted by the text), so text and figures can't drift.
Fails if any LO has more or fewer than one run.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

from plot_datasheet_nf import DATASHEET, IMAGES
from plot_phase_noise import decade_values, plot_compare, plot_run
from results_layout import RESULTS_DIR, unit_dir


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--unit", type=int, default=5)
    args = ap.parse_args()
    runs = defaultdict(list)
    for p in sorted((unit_dir(args.unit) / "phase_noise").glob("lo*GHz_zero_dbm_*.csv")):
        runs[float(re.match(r"lo([\d.]+)GHz", p.name).group(1))].append(p)
    bad = {lo: len(v) for lo, v in runs.items() if len(v) != 1}
    if bad:
        raise SystemExit(f"need exactly one run per LO, got {bad}")
    los = sorted(runs)
    rows = []
    for k, lo in enumerate(los, start=1):
        run = runs[lo][0]
        plot_run(run, IMAGES / f"sec14_fig{k}.pdf")
        meta = json.loads(run.with_suffix(".json").read_text())
        rows.append((lo, decade_values(run), meta["rms_pn_deg"],
                     meta["leak_dbm_at_port_sa"] - meta["unwanted_tone_dbm_at_port"]))

    t = ["% Generated by FR3_Characterization/plot_datasheet_pn.py -- do not edit by hand.",
         # vertical lines at both edges, after LO and before RMS phase error (user, 2026-10-04); plain \hline
         # rules because booktabs rules leave gaps where vertical lines cross them
         "\\begin{tabular}{|l|ccccc|c|}", "\\hline",
         "\\textbf{LO} & \\textbf{100\\,Hz} & \\textbf{1\\,kHz} & \\textbf{10\\,kHz} & \\textbf{100\\,kHz} & "
         "\\textbf{1\\,MHz} & \\textbf{RMS phase error} \\\\",
         " & \\multicolumn{5}{c|}{(dBc/Hz)} & (degrees) \\\\", "\\hline"]
    for lo, v, rms, _ in rows:
        t.append(f"{lo:g}\\,GHz & " + " & ".join(f"{v[d]:.1f}" for d in (100, 1e3, 1e4, 1e5, 1e6))
                 + f" & {rms:.2f} \\\\")
    t += ["\\hline", "\\end{tabular}"]
    body = re.sub(r"-(?=\d)", "−", "\n".join(t[1:]))     # typographic minus on the numbers only
    (DATASHEET / "sections" / "sec14_table.tex").write_text(t[0] + "\n" + body + "\n", encoding="utf-8")

    lo_lo, lo_hi = rows[0], rows[-1]
    expected = 20 * math.log10(lo_hi[0] / lo_lo[0])
    measured = [lo_hi[1][d] - lo_lo[1][d] for d in (100, 1e3, 1e4, 1e5)]
    n = ["% Generated by FR3_Characterization/plot_datasheet_pn.py -- do not edit by hand.",
         f"\\newcommand{{\\pnLoLow}}{{{lo_lo[0]:g}}}",
         f"\\newcommand{{\\pnLoHigh}}{{{lo_hi[0]:g}}}",
         f"\\newcommand{{\\pnScaleExpected}}{{{expected:.1f}}}",
         f"\\newcommand{{\\pnScaleMin}}{{{min(measured):.1f}}}",
         f"\\newcommand{{\\pnScaleMax}}{{{max(measured):.1f}}}",
         f"\\newcommand{{\\pnRmsLow}}{{{lo_lo[2]:.2f}}}",
         f"\\newcommand{{\\pnRmsHigh}}{{{lo_hi[2]:.2f}}}",
         f"\\newcommand{{\\pnCount}}{{{len(rows)}}}",
         f"\\newcommand{{\\pnUnwantedMin}}{{{int(math.floor(min(r[3] for r in rows)))}}}",
         f"\\newcommand{{\\pnUnwantedMax}}{{{int(math.floor(max(r[3] for r in rows)))}}}"]
    # External LO (Pi-Radio OctoLO) at 10 GHz, measured straight into the UXA: comparison figure + numbers
    octo = sorted((RESULTS_DIR / "external_lo").glob("octolo_lo10GHz_*.csv"))
    board10 = runs.get(10.0)
    if octo and board10:
        if len(octo) != 1:
            raise SystemExit(f"need exactly one OctoLO 10 GHz run, got {len(octo)}")
        plot_compare([(board10[0], "Internal LO (10 MHz TCXO + LMX2820)"), (octo[0], "Pi-Radio OctoLO")],
                     "Phase Noise at 10 GHz: Internal LO vs Pi-Radio OctoLO", IMAGES / f"sec14_fig{len(los) + 1}.pdf")
        ob, oo = decade_values(board10[0]), decade_values(octo[0])
        gains = [ob[d] - oo[d] for d in (100, 1e3, 1e4, 1e5)]
        rms_b = json.loads(board10[0].with_suffix(".json").read_text())["rms_pn_deg"]
        rms_o = json.loads(octo[0].with_suffix(".json").read_text())["rms_pn_deg"]
        n += [f"\\newcommand{{\\pnOctoFig}}{{images/sec14_fig{len(los) + 1}.pdf}}",
              f"\\newcommand{{\\pnOctoRms}}{{{rms_o:.2f}}}",
              f"\\newcommand{{\\pnBoardTenRms}}{{{rms_b:.2f}}}",
              f"\\newcommand{{\\pnOctoRmsRatio}}{{{rms_b / rms_o:.1f}}}",
              f"\\newcommand{{\\pnOctoGainMin}}{{{int(round(min(gains)))}}}",
              f"\\newcommand{{\\pnOctoGainMax}}{{{int(round(max(gains)))}}}"]
        print(f"OctoLO: RMS {rms_o:.2f} deg vs on-board {rms_b:.2f} deg; {min(gains):.1f}-{max(gains):.1f} dB lower "
              f"from 100 Hz to 100 kHz")
    (DATASHEET / "sections" / "sec14_numbers.tex").write_text("\n".join(n) + "\n", encoding="utf-8")
    print(f"{len(rows)} LOs: {', '.join(f'{lo:g}' for lo in los)} GHz; scaling {lo_lo[0]:g}->{lo_hi[0]:g} GHz: "
          f"expected {expected:.1f} dB, measured {min(measured):.1f}-{max(measured):.1f} dB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
