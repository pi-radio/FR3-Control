"""Writes FR3-1ch-Datasheet/sections/sec_rx_conditions.tex: the measured LMX2820 die temperature range of each RX-side run of
the 2026-10-09 hot RX re-run (\\condRx<Name>MinC / MaxC), for the sections' "Measurement conditions" paragraphs. A run that
does not exist yet gets a red \\attn placeholder.

    python make_rx_conditions.py
"""
from __future__ import annotations

import csv
from pathlib import Path

from results_layout import unit_dir

OUT = Path(__file__).resolve().parent.parent / "FR3-1ch-Datasheet" / "sections" / "sec_rx_conditions.tex"
RUNS = {"Gain": ("gain_rx_20261009/points.csv", "lmx_temp_c"),
        "Flat": ("flatness_rx_20261009/points.csv", "lmx_temp_c"),
        "Comp": ("compression_rx_20261009/summary.csv", "lmx_temp_c"),
        "Image": ("image_rx_20261009/points.csv", "lmx_temp_c"),
        "Nf": ("rx_nf_optimal_20261009/phase3_gain.csv", "lmx_temperature_c")}


def main() -> None:
    lines = ["% generated by FR3_Characterization/make_rx_conditions.py -- do not edit",
             r"\providecommand{\attn}[1]{\textcolor{red}{\textbf{#1}}}"]
    for name, (rel, col) in RUNS.items():
        p = unit_dir(5) / rel
        t = [float(r[col]) for r in csv.DictReader(open(p, newline=""))] if p.exists() else []
        if name == "Nf" and (p.parent / "phase2_cold_noise.csv").exists():   # both NF steps: gain (A) and noise (B)
            t += [float(r[col]) for r in csv.DictReader(open(p.parent / "phase2_cold_noise.csv", newline=""))]
        if name == "Comp" and p.exists():                         # every step of every sweep, as the TX compression range
            t = [float(r["lmx_temperature_c"]) for f in p.parent.glob("*_FR1_*.csv") for r in csv.DictReader(open(f, newline=""))]
        lo, hi = (f"{min(t):.0f}", f"{max(t):.0f}") if t else (r"\attn{[pending]}", r"\attn{[pending]}")
        lines += [f"\\newcommand{{\\condRx{name}MinC}}{{{lo}}}", f"\\newcommand{{\\condRx{name}MaxC}}{{{hi}}}"]
        print(f"{name:6s} {lo}-{hi} C  ({len(t)} rows, {rel})")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
